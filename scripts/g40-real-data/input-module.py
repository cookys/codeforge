#!/usr/bin/env python3
"""Print the TypeScript input module for scripts/g40-real-data/real-data.test.tsx.

Usage: input-module.py <live_dir>  > real-data.input.ts

Every regular file under the live dir becomes an entry of FILES, keyed by its path under LIVE. Links and
other non-regular files are left out, as forge-stats' mirror reader skips them.
"""
import json
import os
import sys

LIVE = "/live"


def main():
    root = sys.argv[1]
    files = {}
    for d, _, names in os.walk(root, followlinks=False):
        for n in sorted(names):
            p = os.path.join(d, n)
            if os.path.islink(p) or not os.path.isfile(p):
                continue
            rel = os.path.relpath(p, root)
            with open(p, encoding="utf-8") as f:
                files[f"{LIVE}/{rel}"] = f.read()
    print("// generated by scripts/g40-real-data/input-module.py; never committed")
    print(f"export const LIVE = {json.dumps(LIVE)}")
    print(f"export const FILES: Record<string, string> = {json.dumps(files, ensure_ascii=False, indent=1)}")


if __name__ == "__main__":
    main()
