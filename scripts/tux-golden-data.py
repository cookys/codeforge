#!/usr/bin/env python3
"""Bridge JSON fixtures to the Claude hooks sandbox, which only imports code files.

TUX_GOLDEN_DIR selects the source; default is the pinned vendor golden directory.
--check refuses stale checked-in data. An output path supports isolated cross-test copies.
"""
import json
import os
from pathlib import Path
import sys

repo = Path(__file__).resolve().parent.parent
source = Path(os.environ.get('TUX_GOLDEN_DIR', repo / 'plugins/forge-stats/vendor/tux/golden'))
check = sys.argv[1:] == ['--check']
output = Path(sys.argv[1]) if len(sys.argv) == 2 and not check else repo / 'plugins/forge-stats/tests/tux-golden-data.ts'
fixtures = {name: json.loads((source / f'{name}.json').read_text()) for name in
            ['glyphs', 'width-cases', 'pct-cases', 'dur-cases', 'panel-cases']}
body = ('// GENERATED by scripts/tux-golden-data.py; source: TUX_GOLDEN_DIR or vendor/tux/golden.\n'
        '// Claude plugin tests cannot import JSON or node:fs. tux-lock checks this bridge.\n'
        'export const TUX_GOLDEN = ' + json.dumps(fixtures, ensure_ascii=False, indent=2) + ' as const\n')
if check:
    if not output.exists() or output.read_text() != body:
        sys.exit('tux-golden-data: FAIL (stale bridge; run python3 scripts/tux-golden-data.py)')
    print('tux-golden-data: ok')
else:
    output.write_text(body)
